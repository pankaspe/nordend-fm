#pragma once

#include <functional>
#include <memory>
#include <optional>
#include <span>
#include <string>
#include <string_view>
#include <vector>

#include "nordend/core/event_loop.hpp"
#include "nordend/fs/places.hpp"
#include "nordend/views/browser.hpp"

// Plugins: features that are not Nordend's core (network folders today), each in plugins/<id>,
// built in when CMake's NORDEND_PLUGIN_<ID> is on (the default) and switched off at run time
// with [plugins] disabled = ["<id>"] in config.toml. They are compiled into the program, not
// loaded from files: no ABI to keep stable, no foreign code in the process, and a plugin's
// dependencies stay its own (plugins/<id>/CMakeLists.txt).
//
// A plugin offers what it can do through the hooks below; each has a default that does nothing,
// so a plugin overrides only what it needs. New hooks are added here as plugins need them.
namespace nordend::plugin {

// What the app lends a plugin. Loop thread only, like everything here.
struct Host {
    core::EventLoop& loop;
    // The sidebar asks every plugin for its places again (after a mount, say).
    std::function<void()> places_changed;
};

class Plugin {
public:
    Plugin() = default;
    virtual ~Plugin() = default;
    Plugin(const Plugin&) = delete;
    Plugin& operator=(const Plugin&) = delete;
    Plugin(Plugin&&) = delete;
    Plugin& operator=(Plugin&&) = delete;

    // ---- Network locations: bookmarks with a URI (fs::Place::uri) ----

    // The URI schemes this plugin mounts ("smb", "sftp"). Remote bookmarks whose scheme no
    // plugin claims are not shown.
    [[nodiscard]] virtual std::vector<std::string> schemes() const { return {}; }

    // Whether it can mount now (its service is reachable). When it cannot, its bookmarks still
    // show, and choosing one says so.
    [[nodiscard]] virtual bool can_mount() const { return false; }

    // Mounts uri, one of its schemes; done gets the local folder, or an error ("cancelled" when
    // the person gave up). prompts ask the person on the Browser's cards.
    virtual void mount(const std::string& uri, views::Remotes::Prompts prompts,
                       views::Remotes::Mounted done) {
        (void)uri;
        (void)prompts;
        done({}, "not supported");
    }

    virtual void unmount(const std::string& uri, views::Remotes::Done done) {
        (void)uri;
        done("not supported");
    }

    // ---- Sidebar ----

    // The places as the sidebar will show them; a plugin may fill in its own (a mounted share's
    // folder and eject icon), add or drop some.
    [[nodiscard]] virtual std::vector<fs::Place> places(std::vector<fs::Place> places) const {
        return places;
    }
};

// A plugin compiled in: its id (the directory name, the config key) and how to make it.
struct Builtin {
    std::string_view id;
    std::string_view summary;  // one line, for --about
    std::unique_ptr<Plugin> (*make)(Host& host);
};

// Every plugin compiled in, in id order (generated by CMake from the NORDEND_PLUGIN_* options).
[[nodiscard]] std::span<const Builtin> builtin();

// The plugins running: every one compiled in and not disabled, made in id order, destroyed in
// reverse. Loop thread only. Must not outlive the loop.
class Plugins {
public:
    // disabled: ids from [plugins] disabled; unknown ones are logged and ignored.
    Plugins(Host host, const std::vector<std::string>& disabled,
            std::span<const Builtin> available = builtin());
    ~Plugins();

    Plugins(const Plugins&) = delete;
    Plugins& operator=(const Plugins&) = delete;
    Plugins(Plugins&&) = delete;
    Plugins& operator=(Plugins&&) = delete;

    [[nodiscard]] std::vector<std::string_view> running() const;

    // The places after every plugin had its say, without remote bookmarks no plugin mounts.
    [[nodiscard]] std::vector<fs::Place> places(std::vector<fs::Place> places) const;

    // Mounting and unmounting remote bookmarks, each URI going to the plugin of its scheme;
    // nullopt when no running plugin can mount now.
    [[nodiscard]] std::optional<views::Remotes> remotes();

private:
    [[nodiscard]] Plugin* for_uri(std::string_view uri) const;

    Host host_;
    std::vector<std::unique_ptr<Plugin>> plugins_;
    std::vector<std::string_view> ids_;
};

}  // namespace nordend::plugin
